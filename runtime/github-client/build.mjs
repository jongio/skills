import { build } from "esbuild";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..", "..");
const outputs = [
  "skills/ci-hound/scripts/lib/github-client.mjs",
  "skills/pr/scripts/lib/github-client.mjs",
  "extensions/github-client.mjs",
];
const result = await build({
  absWorkingDir: root,
  entryPoints: [resolve(here, "client.mjs")], bundle: true, write: false, platform: "node",
  format: "esm", target: "node22", minify: true, legalComments: "inline",
  banner: { js: 'import { createRequire as __createRequire } from "node:module"; const require = __createRequire(import.meta.url);\n// Generated by runtime/github-client/build.mjs. Do not edit.' },
});
const bundle = result.outputFiles[0].text;
const notices = [];
function licenses(directory) {
  const manifest = JSON.parse(readFileSync(resolve(directory, "package.json"), "utf8"));
  for (const name of ["LICENSE", "LICENSE.md", "LICENSE.txt", "license", "LICENSE-MIT"]) {
    const file = resolve(directory, name);
    if (existsSync(file)) { notices.push(`${manifest.name}@${manifest.version}\n${readFileSync(file, "utf8")}`); break; }
  }
  for (const name of Object.keys(manifest.dependencies || {})) {
    if (notices.some((text) => text.startsWith(`${name}@`))) continue;
    let base = directory;
    while (!existsSync(resolve(base, "node_modules", name, "package.json"))) {
      const parent = dirname(base);
      if (parent === base) throw new Error(`Missing locked dependency ${name}`);
      base = parent;
    }
    licenses(resolve(base, "node_modules", name));
  }
}
for (const name of ["@octokit/core", "undici"]) licenses(resolve(here, "node_modules", name));
const notice = notices.join("\n\n---\n\n").trimEnd() + "\n";
for (const output of outputs) {
  for (const [path, text] of [[resolve(root, output), bundle], [resolve(root, dirname(output), "github-client.LICENSE"), notice]]) {
    if (process.argv.includes("--check")) {
      if (!existsSync(path) || readFileSync(path, "utf8") !== text) throw new Error(`Generated runtime out of date: ${path}`);
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, text);
    }
  }
  const fixtureSource = "// Generated from test/github-fixtures.mjs; do not edit.\n" +
    readFileSync(resolve(root, "test", "github-fixtures.mjs"), "utf8");
  for (const id of ["ci-hound", "pr"]) {
    const file = resolve(root, "skills", id, "test", "github-fixtures.mjs");
    if (process.argv.includes("--check")) {
      if (!existsSync(file) || readFileSync(file, "utf8") !== fixtureSource) throw new Error(`Fixture adapter out of date: ${file}`);
    } else writeFileSync(file, fixtureSource);
  }
}
